public abstract class Potion {
    private String name;
    private int health;
    private int price;
    private int level;
    private int rarity;
    private int type;
    private int rarity; 
    
    public Potion(String name, int health, int price, int level, int rarity, int type, int rarity) {
        this.name = name;
        this.health = health;
        this.price = price;
        this.level = level;
        this.rarity = rarity;
        this.type = type;
        this.rarity = rarity;
    }
}   